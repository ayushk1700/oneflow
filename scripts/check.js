import fs from 'node:fs/promises';
import path from 'node:path';
import assert from 'node:assert/strict';
import { spawnSync } from 'node:child_process';
const manifest = JSON.parse(await fs.readFile('manifest.json', 'utf8'));
assert.equal(manifest.manifest_version, 3);
assert.deepEqual(manifest.permissions, ['storage','alarms','notifications','offscreen','declarativeNetRequest','search','activeTab','scripting']);
assert(!manifest.host_permissions);
const csp = manifest.content_security_policy.extension_pages;
assert(csp.includes("script-src 'self'") && !csp.includes('unsafe-'));
for (const file of [manifest.chrome_url_overrides.newtab, manifest.background.service_worker, ...Object.values(manifest.icons)]) await fs.access(file);
async function walk(dir) { return (await Promise.all((await fs.readdir(dir, { withFileTypes:true })).map(async x => x.isDirectory() ? walk(path.join(dir,x.name)) : path.join(dir,x.name)))).flat(); }
const files = (await Promise.all(['core','newtab','components','background'].map(walk))).flat();
let jsBytes = 0;
for (const file of files) {
  const content = await fs.readFile(file,'utf8');
  if (file.endsWith('.js')) { jsBytes += Buffer.byteLength(content); const check = spawnSync(process.execPath,['--check',file],{encoding:'utf8'}); assert.equal(check.status,0,check.stderr); assert(!/\.innerHTML\s*=|\beval\s*\(/.test(content),`Unsafe rendering: ${file}`); }
  if (file.endsWith('.html')) { assert(!/<script\b[^>]*src=["']https?:/i.test(content)); assert(!/\son\w+=["']/i.test(content)); assert(!/<script\b(?![^>]*\bsrc=)[^>]*>/i.test(content)); }
}
const widgetFiles=JSON.parse(await fs.readFile('scripts/widget-styles.json','utf8'));
const widgetStyles=await Promise.all(widgetFiles.map(async file=>'/* '+file+' */\n'+await fs.readFile(path.join('newtab',file),'utf8')));
assert.equal(await fs.readFile('newtab/widgets.css','utf8'),'/* Generated by scripts/styles.js; edit component styles, then regenerate. */\n'+widgetStyles.join('\n'),'Regenerate widget CSS with node scripts/styles.js');
const appFiles=['../vendor/tailwindcss/3.4.17/tailwind.min.css','tokens.css','widgets.css','newtab.css','foundation.css','panels.css','dashboard.css','system.css'];
const appStyles=await Promise.all(appFiles.map(async file=>'/* '+file+' */\n'+await fs.readFile(path.join('newtab',file),'utf8')));
assert.equal(await fs.readFile('newtab/app.css','utf8'),'/* Generated by scripts/styles.js; edit source styles, then regenerate. */\n'+appStyles.join('\n'),'Regenerate application CSS with node scripts/styles.js');
for (const file of ['newtab/newtab.css','newtab/foundation.css','newtab/panels.css','newtab/dashboard.css']) {
  const source = await fs.readFile(file, 'utf8');
  assert(!/^\s*:root\s*\{/m.test(source), `Shared tokens must stay in newtab/tokens.css: ${file}`);
}
for(const file of ['newtab/index.html'])for(const match of (await fs.readFile(file,'utf8')).matchAll(/<link[^>]+href="([^"]+\.css)"/g)){assert(!/^https?:/.test(match[1]));await fs.access(path.join(path.dirname(file),match[1]));}
const seen = new Set();
async function initialBytes(file) {
  file = path.normalize(file); if (seen.has(file)) return 0; seen.add(file);
  const source = await fs.readFile(file, 'utf8'); let bytes = Buffer.byteLength(source);
  for (const match of source.matchAll(/(?:import|export)\s+(?:[^;'"\n]*?from\s*)?['"](\.[^'"]+)['"]/g)) bytes += await initialBytes(path.join(path.dirname(file), match[1]));
  return bytes;
}
const eagerBytes = await initialBytes('newtab/newtab.js');
assert(eagerBytes < 150 * 1024, `Initial JS over budget: ${eagerBytes}`);
const quotes = JSON.parse(await fs.readFile('data/quotes.json','utf8'));
assert(quotes.length >= 500); assert.equal(new Set(quotes.map(x=>x.id)).size,quotes.length); assert.equal(new Set(quotes.map(x=>x.text)).size,quotes.length);
console.log(`PASS: manifest references, CSP, syntax, safe DOM rendering, ${quotes.length} unique local quotes.`);
console.log(`Initial application JavaScript: ${(eagerBytes/1024).toFixed(1)} KiB / 150 KiB budget.`);
