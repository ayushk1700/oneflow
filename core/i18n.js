const keys = new Map(Object.entries(en).map(([k, v]) => [v, k]));
/** Resolve a catalog key or known English label with text-safe interpolation. */
export function t(key, params = {}) {
  const id = en[key] !== undefined ? key : keys.get(key);
  const text = packs[language]?.[id] ?? en[id] ?? key;
  return text.replace(/\{(p\d+)\}/g, (all, name) => params[name] === undefined ? all : String(params[name]));
}
export function setLanguage(value) {
  language = value in packs ? value : 'en';
  if (globalThis.document) document.documentElement.lang = language;
}
/** Translate only the static shell, before user content is mounted. */
export function translateShell(root = document.body) {
  const walk = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
  while (walk.nextNode()) {
    const n = walk.currentNode,
      value = n.textContent.trim();
    if (keys.has(value)) n.textContent = n.textContent.replace(value, t(value));
  }
  for (const n of root.querySelectorAll('[aria-label],[title]')) for (const a of ['aria-label', 'title']) if (n.hasAttribute(a)) n.setAttribute(a, t(n.getAttribute(a)));
}
